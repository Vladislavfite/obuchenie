export function buildCoursePrompt(text: string, opts: { count: number; difficulty: string; practical: boolean; images: boolean }): string {
  const difficultyLabel =
    opts.difficulty === 'basic' ? 'базовый (проверка знания основных требований)'
    : opts.difficulty === 'advanced' ? 'продвинутый (разбор нетиповых ситуаций)'
    : 'средний (применение требований на практике)';

  return [
    `Уровень сложности: ${difficultyLabel}.`,
    `Количество вопросов: ${opts.count}.`,
    opts.practical ? 'Часть вопросов должна быть ситуационными (isPractical: true).' : '',
    opts.images ? 'Где иллюстрация помогает пониманию, заполни imagePrompt.' : 'Поле imagePrompt оставляй пустым.',
    '',
    'Текст документа:',
    '---',
    text,
    '---',
  ].filter(Boolean).join('\n');
}
